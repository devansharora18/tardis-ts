import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve('.')
const docsDir = path.join(root, 'docs')

const groups = [
  ['Introduction', ['../README.md']],
  ['Guides', ['TSX.md', 'EDITORS.md', 'SHEETS.md', 'ELECTRON.md', 'BENCHMARKS.md']],
  ['Native', ['native/architecture.md', 'native/protocol.md', 'PACKAGING.md']],
  ['Project', ['DECISIONS.md', 'PLAN.md', 'TODO.md', 'RECON.md']],
  ['ADRs', [
    'adr/0001-native-core-architecture.md',
    'adr/0002-native-target-in-monorepo.md',
    'adr/0003-tsx-only-v2.md',
    'adr/0004-web-dom-adapter.md',
    'adr/0005-runtime-engine-and-performance.md',
  ]],
]

function titleOf(text, fallback) {
  const match = /^#\s+(.+)$/m.exec(text)
  return match ? match[1].trim() : fallback
}

function slugOf(file) {
  return file
    .replace('../', '')
    .replace(/\.md$/, '')
    .replace(/[/]/g, '-')
    .toLowerCase()
}

const sections = []
for (const [group, files] of groups) {
  for (const file of files) {
    const full = file.startsWith('../') ? path.join(root, file.slice(3)) : path.join(docsDir, file)
    if (!fs.existsSync(full)) continue
    const body = fs
      .readFileSync(full, 'utf8')
      .replace(/^\[!\[[^\n]+\n?/m, '')
      .replace(/^\[!\[[^\n]+\n?/gm, '')
    sections.push({
      group,
      slug: slugOf(file),
      title: titleOf(body, path.basename(file, '.md')),
      file: file.startsWith('../') ? file.slice(3) : file,
      body,
    })
  }
}

const output = `// Generated by scripts/build-docs-content.mjs. Do not edit.
export interface DocSection {
  group: string
  slug: string
  title: string
  file: string
  body: string
}

export const sections: DocSection[] = ${JSON.stringify(sections, null, 2)}
`
fs.writeFileSync(path.join(root, 'site/docs/content.generated.ts'), output)
console.log(`docs: ${sections.length} sections -> site/docs/content.generated.ts`)
